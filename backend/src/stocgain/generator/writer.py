"""Atomic deterministic CSV output and checksummed provenance (docs/06 §9)."""

import csv
import hashlib
import json
import os
import shutil
import tempfile
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from stocgain.db.models import Base
from stocgain.generator.simulation import Dataset


def file_checksums(path: Path) -> dict[str, str]:
    """Hash CSV bytes in sorted filename order; timestamps never enter hashes."""
    return {
        p.name: hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(path.glob("*.csv"))
    }


def combined_checksum(checksums: dict[str, str]) -> str:
    """Hash filename + file digest records, sorted lexicographically."""
    return hashlib.sha256(
        "".join(f"{name}:{checksums[name]}\n" for name in sorted(checksums)).encode()
    ).hexdigest()


def write_dataset(dataset: Dataset, destination: Path) -> dict[str, Any]:
    """Write a complete directory atomically; restore prior output if publish fails."""
    destination = destination.resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    temp = Path(tempfile.mkdtemp(prefix=".stocgain-", dir=destination.parent))
    backup = destination.with_name(destination.name + ".previous")
    try:
        for name, rows in dataset.tables.items():
            schema = "sim_truth" if name == "latent_demand" else "ops"
            columns = list(Base.metadata.tables[f"{schema}.{name}"].columns)
            with (temp / f"{name}.csv").open("w", newline="", encoding="utf-8") as f:
                writer = csv.writer(f, lineterminator="\n")
                writer.writerow([c.name for c in columns])
                for row in rows:
                    writer.writerow(
                        [
                            ""
                            if value is None
                            else str(value).lower()
                            if isinstance(value, bool)
                            else format(value, f".{column.type.scale}f")
                            if isinstance(value, (int, float))
                            and hasattr(column.type, "scale")
                            else value
                            for column, value in zip(columns, row, strict=True)
                        ]
                    )
        checksums = file_checksums(temp)
        config = dataset.config
        manifest = {
            "data_origin": "synthetic",
            "generator_version": config.raw["generator_version"],
            "preset": config.preset,
            "seed": dataset.seed,
            "history_start_date": config.history_start.isoformat(),
            "history_end_date": config.history_end.isoformat(),
            "burn_in_days": config.burn_in_days,
            "events_enabled": config.raw["events"]["enabled"],
            "generated_at": datetime.now(UTC).isoformat(),
            "row_counts": {n: len(rows) for n, rows in dataset.tables.items()},
            "file_checksums": checksums,
            "content_checksum": combined_checksum(checksums),
        }
        manifest["notes"] = (
            f"Simulated Retail Dataset. All stores, products, suppliers, prices, sales, inventory, and purchase orders in stocgain were generated by the stocgain simulator (version {manifest['generator_version']}, preset {config.preset}, seed {dataset.seed}) for the period {config.history_start} to {config.history_end}. City names are real US metros; all store, product, brand, and supplier names are fictional, and any resemblance to real businesses is coincidental. The data is not derived from, and does not represent, any real company. Results describe the simulation and are not evidence about real retail operations."
        )
        (temp / "manifest.json").write_text(
            json.dumps(manifest, sort_keys=True, indent=2) + "\n"
        )
        if backup.exists():
            raise FileExistsError(f"Recover or remove prior backup first: {backup}")
        if destination.exists():
            os.replace(destination, backup)
        try:
            os.replace(temp, destination)
        except BaseException:
            if backup.exists():
                os.replace(backup, destination)
            raise
        if backup.exists():
            shutil.rmtree(backup)
        return manifest
    finally:
        if temp.exists():
            shutil.rmtree(temp)
